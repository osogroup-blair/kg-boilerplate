"""The graph half of a deletion (ADR-018, ADR-044): the ONLY deletion code that touches Neo4j.

Graphiti's own episode removal is not used. It deletes what IT believes an episode owns, which can take a retained fact's edge or a surviving entity's node with it (GR-08).
The platform knows what must go (it listed it from Postgres) and what must stay, so it removes exactly the listed episodes, nodes and edges, empties the derived summaries of
surviving neighbours that cite the subject (never regenerated by a model here), prunes the references that now dangle, sweeps extraction debris no one owns, and then makes the
survivors equal Postgres again from the FINAL Postgres state. It runs under the workspace's graph lock, so it never races an extraction or a projection.
"""

from __future__ import annotations

import uuid

from kg_db.session import tenant_session
from kg_domain.principal import WorkspaceContext
from kg_governance.deletion.ports import GraphListing, GraphPurgeCounts, GraphResidual
from kg_graph.service import GraphService
from kg_obs.logging import get_logger
from sqlalchemy import text
from sqlalchemy.ext.asyncio import AsyncEngine

from kg_knowledge.graphlock import GraphLock
from kg_knowledge.projection import Projector

log = get_logger("kg.graph.purge")


GraphHandle = GraphService  # what the packages above kg_knowledge name when they hold the graph (kg_memory may not import kg_graph itself)


class GraphPurger:
    def __init__(self, engine: AsyncEngine, graph: GraphService, projector: Projector, lock: GraphLock):
        self._engine, self._graph, self._projector, self._lock = engine, graph, projector, lock

    async def list_for(
        self, ctx: WorkspaceContext, *, episode_uuids: list[str], node_uuids: list[str], edge_uuids: list[str], terms: list[str]
    ) -> GraphListing:
        g = self._graph.scoped(ctx)
        have_nodes, have_edges = await g.list_uuids()
        nodes = sorted(set(node_uuids) & have_nodes)
        edges = sorted(set(edge_uuids) & have_edges)
        summaries = await g.summary_hits(terms, exclude=nodes)
        return GraphListing(episode_uuids=sorted(set(episode_uuids)), node_uuids=nodes, edge_uuids=edges, summary_nodes=summaries)

    async def purge(
        self,
        ctx: WorkspaceContext,
        *,
        episode_uuids: list[str],
        node_uuids: list[str],
        edge_uuids: list[str],
        summary_nodes: list[str],
        reproject_nodes: list[str],
        reproject_edges: list[str],
    ) -> GraphPurgeCounts:
        g = self._graph.scoped(ctx)
        out = GraphPurgeCounts()
        async with self._lock.hold(ctx.workspace_id, wait_seconds=120.0):
            out.edges = await g.delete_edges_by_uuid(edge_uuids)
            for u in episode_uuids:
                out.episodes += int(await g.remove_episode_scoped(u))
            out.nodes = await g.delete_nodes_by_uuid(node_uuids)
            out.summaries_cleared = await g.clear_summaries(summary_nodes)
            out.dangling_pruned = await g.prune_dangling_refs()
            if (
                reproject_nodes or reproject_edges
            ):  # (d) the survivors, from the final Postgres state; a failure raises and the step runs again
                report = await self._projector.restore_scope(
                    ctx, entity_ids=[uuid.UUID(x) for x in reproject_nodes], fact_ids=[uuid.UUID(x) for x in reproject_edges]
                )
                out.reprojected = report.repaired
                if report.unsettled:
                    raise RuntimeError("graph_unavailable")
            async with tenant_session(self._engine, ctx) as conn:
                known = [
                    str(r.id)
                    for r in (await conn.execute(text("SELECT id FROM entities WHERE workspace_id = :ws"), {"ws": ctx.workspace_id})).all()
                ]
            out.orphans_swept = await g.orphan_sweep(known)  # (f) scoped to this group, and never a node the platform owns
            await self._clear_inactive_namespaces(ctx)  # P9: no other copy of the subject may outlive the purge
        log.info("graph_purged", episodes=out.episodes, nodes=out.nodes, edges=out.edges, summaries=out.summaries_cleared)
        return out

    async def _clear_inactive_namespaces(self, ctx: WorkspaceContext) -> None:
        """A reindex keeps the previous namespace for rollback and builds the next one beside the live one. Both are copies of the workspace's graph, so a deletion removes them
        (rollback is forfeited and a build in progress fails with `deletion_during_build`): the purge is the deletion's promise, the rollback window is a convenience."""
        async with tenant_session(self._engine, ctx) as conn:
            rows = (
                await conn.execute(
                    text(
                        "SELECT namespace FROM workspace_graph_namespaces WHERE workspace_id = :ws AND status IN ('building','retired') AND cleared_at IS NULL"
                    ),
                    {"ws": ctx.workspace_id},
                )
            ).all()
        if not rows:
            return
        rg = self._graph.reindexer(ctx)
        for r in rows:
            await rg.clear(r.namespace)
        async with tenant_session(self._engine, ctx) as conn:
            await conn.execute(
                text(
                    "UPDATE workspace_graph_namespaces SET status = 'retired', retired_at = COALESCE(retired_at, now()), cleared_at = now() WHERE workspace_id = :ws AND namespace = ANY(:n)"
                ),
                {"ws": ctx.workspace_id, "n": [r.namespace for r in rows]},
            )
            await conn.execute(
                text(
                    "UPDATE reindex_runs SET status = 'failed', error_code = 'deletion_during_build', updated_at = now() "
                    "WHERE workspace_id = :ws AND status IN ('building','catching_up','ready')"
                ),
                {"ws": ctx.workspace_id},
            )

    async def scan(self, ctx: WorkspaceContext, *, terms: list[str], ids: list[str]) -> list[GraphResidual]:
        g = self._graph.scoped(ctx)
        return [GraphResidual(loc, n) for loc, n in await g.scan_text(terms, ids)]

    async def clear_workspace(self, ctx: WorkspaceContext) -> int:
        async with self._lock.hold(ctx.workspace_id, wait_seconds=120.0):
            g = self._graph.scoped(ctx)
            return await g.clear_group() + await g.clear_staging_groups()
